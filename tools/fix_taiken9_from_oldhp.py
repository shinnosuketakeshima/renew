def main() -> int:
    src = ROOT / "docs" / "oldHP" / "taiken9.html"
    if not src.is_file():
        print("missing docs/oldHP/taiken9.html", file=__import__("sys").stderr)
        return 1

    blocks = hand_blocks()
    h1_full = "参加者の声：ネパール　高橋法子様　2005年9月ご参加"
    out = r.page_html(
        9,
        h1_full,
        "参加者の声：高橋法子さま",
        blocks,
        False,
        "ネパール",
        "2005年9月ご参加",
    )
    (ROOT / "taiken9.html").write_text(out, encoding="utf-8")

    from audit_taiken_vs_oldhp import new_article_text, old_article_text

    ratio = len(new_article_text(ROOT / "taiken9.html")) / len(old_article_text(src))
    print(f"Wrote taiken9.html ({len(blocks)} blocks, ratio={ratio:.3f})")
    return 0 if ratio > 0.85 else 1


if __name__ == "__main__":
    raise SystemExit(main())
